"""Простое приложение с интеграцией модулей (задание 1734).

Приложение состоит из трёх логических модулей (секций кода):
ввод данных (число от пользователя), обработка (математические
операции: квадрат и удвоение) и вывод результатов на экран.
Данные между модулями передаются через параметры и возвращаемые
значения функций.
"""


# ---------- модуль ввода данных ----------

def input_number():
    """Запрашивает у пользователя число и возвращает его.

    На нечисловом вводе выбрасывает ValueError.
    """
    raw = input("Введите число: ")
    return float(raw)


# ---------- модуль обработки данных ----------

def square(number):
    """Возвращает квадрат числа."""
    return number ** 2


def double(number):
    """Возвращает удвоенное число."""
    return number * 2


# ---------- модуль вывода результатов ----------

def print_result(original, squared, doubled):
    """Выводит исходное число и результаты его обработки."""
    print("Вы ввели:", original)
    print("Квадрат числа:", squared)
    print("Удвоенное число:", doubled)


# ---------- основная часть: связывание модулей ----------

def main():
    """Точка входа: передаёт данные между модулями."""
    try:
        # модуль ввода -> число
        number = input_number()
    except ValueError:
        print("Ошибка: нужно вводить число")
        return

    # число -> модуль обработки -> результаты
    squared = square(number)
    doubled = double(number)

    # результаты -> модуль вывода
    print_result(number, squared, doubled)


if __name__ == "__main__":
    main()
