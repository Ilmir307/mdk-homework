"""Скрипт с утечками памяти и непокрытым кодом (исходный, задание 1603)."""

CACHE = []  # глобальный кэш, который растёт бесконечно


def process_data(values):
    """Обрабатывает данные с двумя проблемами.

    1. Каждый вызов бесконтрольно раздувает глобальный CACHE
       (утечка памяти: объёмные строки копятся навсегда).
    2. Файл открывается без with и не закрывается
       (утечка файлового дескриптора).
    """
    for value in values:
        CACHE.append(str(value) * 1000)
    f = open("task1603-log.txt", "a", encoding="utf-8")
    f.write("обработано " + str(len(values)) + "\n")
    # файл не закрыт!
    return len(values)


def unused_branch(values):
    """Мёртвая функция: нигде не вызывается (покрытие < 100%)."""
    return [v * 2 for v in values]
